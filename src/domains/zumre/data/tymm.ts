export function topicToString(t: TYMMTopic): string {
  return `${t.code} · ${t.topic}`
}

export function parseTopicString(s: string): { code: string; topic: string } {
  const m = s.match(/^([A-Z]{2,4}\.\d{1,2}\.\d{1,2}) · (.+)$/)
  if (m) return { code: m[1], topic: m[2] }
  return { code: '', topic: s }
}
